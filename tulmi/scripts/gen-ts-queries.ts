/**
 * Embeds the tree-sitter queries (src/code/project/treesitter/queries/<language>/<kind>.scm) in a TypeScript module, queries.gen.ts.
 *
 * The queries are written as .scm files, the way tree-sitter tooling reads them, but the project is compiled with tsc and the jobs Worker is bundled by
 * esbuild, and neither carries a loose text file along. So the files are the source and the module is their copy; tests/code-project-treesitter-queries.test.ts
 * fails when the two differ. After editing a .scm file: `npm run gen:queries`.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "code", "project", "treesitter");

export function collect(dir = join(root, "queries")): Record<string, string> {
  const out: Record<string, string> = {};
  const walk = (d: string) => {
    for (const name of readdirSync(d).sort()) {
      const p = join(d, name);
      if (statSync(p).isDirectory()) walk(p);
      else if (name.endsWith(".scm")) out[relative(join(root, "queries"), p).split(sep).join("/")] = readFileSync(p, "utf8");
    }
  };
  walk(dir);
  return out;
}

export function render(files: Record<string, string>): string {
  const body = Object.entries(files).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n");
  return `// GENERATED by scripts/gen-ts-queries.ts from queries/**/*.scm. Do not edit by hand: edit the .scm files and run \`npm run gen:queries\`.\n`
    + `export const QUERY_FILES: Readonly<Record<string, string>> = {\n${body}\n};\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const out = join(root, "queries.gen.ts");
  writeFileSync(out, render(collect()));
  console.log(`wrote ${relative(process.cwd(), out)} (${Object.keys(collect()).length} files)`);
}
