/**
 * THE PROJECT BRAIN READS CODE WITH TREE-SITTER WHERE IT CAN, AND WITH ITS REGEXES WHERE IT CANNOT (src/code/project/treesitter, symbols.ts, graph.ts, texts.ts).
 *
 * Held here:
 *   - the .scm queries and their TypeScript copy are the same text (npm run gen:queries);
 *   - all fourteen grammars load on Node, lazily and only when a file needs them;
 *   - against the hand-written gold of evals/symbols (every language the brain reads), the parser's definitions, routes and imports are right, and the
 *     regex reader's are measurably worse (the measured numbers are in docs/code-project-brain.md; the bounds here are what must not slip);
 *   - against the TypeScript compiler's own reading of real files (a slice of tulmi/src), the parser agrees with it;
 *   - the regex path is what answers whenever the parser cannot: switched off, no grammar, a language with no grammar, a file too long-lined, a wreck of a file;
 *   - the facts the parser adds that a regex has no way to get: where a definition ENDS, what a file REFERS to, JSX text and attributes.
 */
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { collect, render } from "../scripts/gen-ts-queries.js";
import { QUERY_FILES } from "../src/code/project/treesitter/queries.gen.js";
import { GRAMMARS, analyse, ensureGrammars, forgetFacts, grammarsFor, pickGrammar, setGrammarSource, treeSitter, type GrammarSource } from "../src/code/project/treesitter/index.js";
import { nodeSource } from "../src/code/project/treesitter/nodeSource.js";
import { PARSE_MAX_LINE } from "../src/code/project/treesitter/host.js";
import { extractImports, extractImportsRegex } from "../src/code/project/graph.js";
import { extractSymbols, extractSymbolsRegex } from "../src/code/project/symbols.js";
import { extractTexts } from "../src/code/project/texts.js";
import { GOLD } from "../evals/symbols/gold.js";
import { add, emptyTally, f1, precision, recall } from "../evals/symbols/score.js";
import { corpusRows, fixtureRows, tsFiles } from "../evals/symbols/run.js";

beforeAll(async () => {
  treeSitter.disable(false);
  await ensureGrammars(GOLD.map((g) => ({ path: g.path, lang: g.langName })));
});
afterAll(() => {
  setGrammarSource(null);
  treeSitter.disable(false);
  forgetFacts();
});

describe("the queries", () => {
  it("are the .scm files, copied into queries.gen.ts (run `npm run gen:queries` after editing one)", () => {
    const files = collect();
    expect(Object.keys(files).length).toBeGreaterThan(30);
    expect(QUERY_FILES).toEqual(files);
    expect(render(files)).toContain("GENERATED by scripts/gen-ts-queries.ts");
  });
});

describe("the grammars", () => {
  it("are fourteen, each carried by the Node source and loaded on demand", async () => {
    expect(GRAMMARS.length).toBe(14);
    const src = nodeSource();
    for (const id of GRAMMARS) expect(src.has(id)).toBe(true);
    const ready = await ensureGrammars(GRAMMARS.map((id) => ({ path: `x.${id}`, lang: ({ typescript: "TypeScript", tsx: "TypeScript", javascript: "JavaScript", python: "Python", go: "Go", rust: "Rust", java: "Java", kotlin: "Kotlin", ruby: "Ruby", php: "PHP", swift: "Swift", c_sharp: "C#", dart: "Dart", html: "HTML" } as const)[id] })));
    expect(ready).toContain("typescript");
    expect(ready).toContain("python");
    const status = treeSitter.status();
    expect(status.engine).toBe(true);
    expect(status.failed).toEqual({});
    expect(status.absent).toEqual([]);
  });
  it("are picked by language and extension; a language with none is read by regex; a Vue file's script is parsed on its own", () => {
    expect(pickGrammar("a.ts", "TypeScript", "")?.id).toBe("typescript");
    expect(pickGrammar("a.tsx", "TypeScript", "")?.id).toBe("tsx");
    expect(pickGrammar("a.jsx", "JavaScript", "")?.id).toBe("javascript");
    expect(pickGrammar("README.md", "Markdown", "")).toBeNull();
    expect(pickGrammar("a.sql", "SQL", "")).toBeNull();
    const vue = pickGrammar("A.vue", "Vue", "<template><p/></template>\n<script lang=\"ts\">\nexport const a = 1;\n</script>\n");
    expect(vue?.id).toBe("typescript");
    expect(vue?.lineOffset).toBe(1);
    expect(vue?.code).toContain("export const a");
    expect(pickGrammar("A.vue", "Vue", "<template></template>")).toBeNull();
    expect(grammarsFor([{ path: "a.ts", lang: "TypeScript" }, { path: "b.py", lang: "Python" }, { path: "c.md", lang: "Markdown" }]).sort()).toEqual(["python", "typescript"]);
  });
});

describe("against the gold, per language", () => {
  it("reads every definition, route and import of the fixtures, where the regex misses and invents some", async () => {
    forgetFacts();
    const fx = await fixtureRows();
    expect(fx.defs.length).toBe(12); // TypeScript and TSX are two grammars, one language
    const rx = emptyTally(), ts = emptyTally();
    for (const row of fx.defs) {
      add(rx, row.regex);
      add(ts, row.treeSitter);
      // no language is worse for the parser
      expect(f1(row.treeSitter), row.name).toBeGreaterThanOrEqual(f1(row.regex));
      expect(precision(row.treeSitter), row.name).toBeGreaterThanOrEqual(0.97);
      expect(recall(row.treeSitter), row.name).toBeGreaterThanOrEqual(0.97);
    }
    expect(precision(ts)).toBeGreaterThanOrEqual(0.99);
    expect(recall(ts)).toBeGreaterThanOrEqual(0.99);
    expect(recall(ts) - recall(rx)).toBeGreaterThan(0.2);
    expect(precision(ts)).toBeGreaterThan(precision(rx));
    expect(f1(fx.routes.treeSitter)).toBeGreaterThanOrEqual(0.97);
    expect(f1(fx.routes.treeSitter)).toBeGreaterThan(f1(fx.routes.regex));
    expect(f1(fx.imports.treeSitter)).toBeGreaterThanOrEqual(0.99);
    expect(f1(fx.imports.treeSitter)).toBeGreaterThanOrEqual(f1(fx.imports.regex));
  }, 120_000);
});

describe("against the TypeScript compiler, on real files", () => {
  it("agrees with it on a slice of tulmi/src: every exported definition, with its flag and line", async () => {
    forgetFacts();
    const files = tsFiles().filter((_, i) => i % 6 === 0);
    expect(files.length).toBeGreaterThan(50);
    const c = await corpusRows(files);
    expect(c.files).toBeGreaterThan(40);
    const exported = c.buckets.exported;
    const all = c.buckets.all;
    expect(precision(exported.treeSitter)).toBeGreaterThanOrEqual(0.995);
    expect(recall(exported.treeSitter)).toBeGreaterThanOrEqual(0.995);
    expect(precision(all.treeSitter)).toBeGreaterThanOrEqual(0.99);
    expect(recall(all.treeSitter)).toBeGreaterThanOrEqual(0.99);
    expect(recall(all.treeSitter)).toBeGreaterThan(recall(all.regex));
    expect(all.treeSitter.endN).toBeGreaterThan(0);
    expect(all.treeSitter.endOk / all.treeSitter.endN).toBeGreaterThanOrEqual(0.99);
    expect(c.imports.treeSitter.fp).toBeLessThanOrEqual(c.imports.regex.fp);
    expect(recall(c.imports.treeSitter)).toBeGreaterThanOrEqual(0.995);
  }, 180_000);
});

const SAMPLE = [
  "import express from 'express';",
  "import { helper } from './helper';",
  "const app = express();",
  "",
  "export class Service {",
  "  run(input: string) {",
  "    const out = helper(input);",
  "    return out.trim();",
  "  }",
  "}",
  "",
  "export function startServer(port: number) {",
  "  app.get('/health', (req, res) => res.send('ok'));",
  "  return new Service().run(String(port));",
  "}",
  "",
].join("\n");

describe("what the parser adds", () => {
  it("says where a definition ends, which the regex cannot", () => {
    forgetFacts();
    const ts = extractSymbols("src/server.ts", "TypeScript", SAMPLE);
    const rx = extractSymbolsRegex("src/server.ts", "TypeScript", SAMPLE);
    const fn = ts.find((s) => s.name === "startServer")!;
    expect(fn.line).toBe(12);
    expect(fn.endLine).toBe(15);
    expect(ts.find((s) => s.name === "Service")?.endLine).toBe(10);
    expect(ts.find((s) => s.name === "Service.run")).toBeTruthy();
    expect(rx.find((s) => s.name === "startServer")?.endLine).toBeUndefined();
    expect(ts.filter((s) => s.kind === "route").map((s) => `${s.method} ${s.path}`)).toEqual(["GET /health"]);
  });
  it("reads what a file refers to: calls, constructors, base classes and types, not its own definitions", () => {
    forgetFacts();
    const facts = analyse("src/server.ts", "TypeScript", SAMPLE)!;
    const names = new Map(facts.refs);
    expect(names.has("helper")).toBe(true);
    expect(names.has("Service")).toBe(true);
    expect(names.has("startServer")).toBe(false);
    expect(names.has("log")).toBe(false);
    expect(facts.imports.map((i) => i.spec).sort()).toEqual(["./helper", "express"]);
  });
  it("reads the words a person sees in JSX and HTML, and an attribute apart from a text", () => {
    forgetFacts();
    const jsx = "export const Hero = () => (\n  <section>\n    <h1>Welcome back</h1>\n    <img alt=\"Our team at work\" src=\"/team.png\" />\n    <Button label=\"Sign in\">Continue with email</Button>\n  </section>\n);\n";
    const hits = extractTexts("src/Hero.tsx", "TypeScript", jsx);
    const words = hits.map((h) => h.text);
    expect(words).toEqual(expect.arrayContaining(["Welcome back", "Continue with email"]));
    expect(words.some((w) => w.includes("/team.png"))).toBe(false);
    const html = "<html><body><h1>Pricing</h1><p>Start free today.</p><a href=\"/x\" title=\"Go to checkout\">Buy</a></body></html>";
    expect(extractTexts("index.html", "HTML", html).map((h) => h.text)).toEqual(expect.arrayContaining(["Pricing", "Start free today."]));
  });
  it("tells imports as the language writes them", () => {
    forgetFacts();
    const py = "import os\nfrom . import sibling\nfrom ..pkg.mod import thing as other\n";
    const specs = extractImports("pkg/a.py", "Python", py).map((i) => `${".".repeat(i.level ?? 0)}${i.spec}`).sort();
    expect(specs).toEqual(expect.arrayContaining(["os"]));
    expect(specs.some((s) => s.startsWith(".."))).toBe(true);
    const go = "package main\nimport (\n  \"fmt\"\n  \"example.com/app/store\"\n)\n";
    expect(extractImports("main.go", "Go", go).map((i) => i.spec).sort()).toEqual(["example.com/app/store", "fmt"]);
  });
});

describe("the regex path answers whenever the parser cannot", () => {
  it("is what runs when the parser is switched off (CODE_TREE_SITTER=false)", () => {
    treeSitter.disable(true);
    try {
      forgetFacts();
      expect(analyse("src/server.ts", "TypeScript", SAMPLE)).toBeNull();
      expect(extractSymbols("src/server.ts", "TypeScript", SAMPLE)).toEqual(extractSymbolsRegex("src/server.ts", "TypeScript", SAMPLE));
      expect(extractImports("src/server.ts", "TypeScript", SAMPLE)).toEqual(extractImportsRegex("src/server.ts", "TypeScript", SAMPLE));
    } finally {
      treeSitter.disable(false);
      forgetFacts();
    }
  });
  it("is what runs for a language with no grammar", () => {
    forgetFacts();
    expect(analyse("notes.md", "Markdown", "# Title\n\nSome words.\n")).toBeNull();
    expect(analyse("q.sql", "SQL", "create table t (a int);")).toBeNull();
  });
  it("is what runs for a file the parser declines: a line over the limit, and a file that is mostly syntax error", () => {
    forgetFacts();
    const minified = `export const data = "${"x".repeat(PARSE_MAX_LINE + 50)}";\nexport function ok() { return 1; }\n`;
    expect(analyse("src/min.ts", "TypeScript", minified)).toBeNull();
    expect(extractSymbols("src/min.ts", "TypeScript", minified).map((s) => s.name)).toEqual(extractSymbolsRegex("src/min.ts", "TypeScript", minified).map((s) => s.name));
    const wreck = "}{)(;;]] ".repeat(400);
    expect(analyse("src/wreck.ts", "TypeScript", wreck)).toBeNull();
    expect(() => extractSymbols("src/wreck.ts", "TypeScript", wreck)).not.toThrow();
  });
  it("is what runs when this runtime carries no grammar, and says so (a Worker with a small bundle)", async () => {
    const none: GrammarSource = { has: () => false, core: () => Promise.reject(new Error("no engine")), grammar: () => Promise.reject(new Error("no grammar")) };
    try {
      setGrammarSource(none);
      forgetFacts();
      expect(await ensureGrammars([{ path: "a.kt", lang: "Kotlin" }])).toEqual([]);
      expect(treeSitter.status().absent).toContain("kotlin");
      expect(analyse("A.kt", "Kotlin", "class A { fun b() {} }")).toBeNull();
      expect(extractSymbols("A.kt", "Kotlin", "class A { fun b() {} }").map((s) => s.name)).toContain("A");
    } finally {
      setGrammarSource(null);
      await ensureGrammars(GOLD.map((g) => ({ path: g.path, lang: g.langName })));
      forgetFacts();
    }
  });
  it("is what runs when a grammar will not load: the failure is remembered, the language read by regex, nothing thrown", async () => {
    const real = nodeSource();
    const broken: GrammarSource = { ...real, grammar: (id) => (id === "ruby" ? Promise.resolve(new Uint8Array([0, 97, 115, 109, 1, 0, 0, 0]) as never) : real.grammar(id)) };
    try {
      setGrammarSource(broken);
      forgetFacts();
      const ready = await ensureGrammars([{ path: "a.rb", lang: "Ruby" }, { path: "a.py", lang: "Python" }]);
      expect(ready).toContain("python");
      expect(ready).not.toContain("ruby");
      expect(Object.keys(treeSitter.status().failed)).toContain("ruby");
      expect(analyse("a.rb", "Ruby", "class A\n  def b; end\nend\n")).toBeNull();
      expect(analyse("a.py", "Python", "def b():\n    return 1\n")).not.toBeNull();
    } finally {
      setGrammarSource(null);
      await ensureGrammars(GOLD.map((g) => ({ path: g.path, lang: g.langName })));
      forgetFacts();
    }
  });
  it("remembers whether a grammar is installed rather than searching the disk for it on every build", () => {
    const src = nodeSource();
    const t = performance.now();
    for (let i = 0; i < 5000; i += 1) src.has("typescript");
    expect(performance.now() - t).toBeLessThan(500);
  });
});
